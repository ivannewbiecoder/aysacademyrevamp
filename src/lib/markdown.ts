import type { Element, ElementContent, Root, RootContent } from "hast";
import rehypeKatex from "rehype-katex";
import rehypeSanitize, { defaultSchema, type Options as SanitizeSchema } from "rehype-sanitize";
import rehypeSlug from "rehype-slug";
import rehypeStringify from "rehype-stringify";
import remarkGfm from "remark-gfm";
import remarkMath from "remark-math";
import remarkParse from "remark-parse";
import remarkRehype from "remark-rehype";
import { unified } from "unified";

/**
 * Markdown is the single storage format for articles, problems and explanations.
 *
 * Security model:
 *  - Raw HTML inside markdown is dropped (remark-rehype without allowDangerousHtml).
 *  - The resulting tree is sanitized with a GitHub-style allowlist, which also
 *    strips `javascript:` and other unsafe URL protocols.
 *  - KaTeX runs *after* sanitizing and with `trust: false`, so only math markup
 *    generated by KaTeX itself is added.
 */
const schema: SanitizeSchema = {
  ...defaultSchema,
  // Keep heading ids readable; rehype-slug assigns clean ids after sanitizing.
  clobberPrefix: "",
  clobber: [],
  attributes: {
    ...defaultSchema.attributes,
    code: [
      ...(defaultSchema.attributes?.code ?? []),
      ["className", /^language-[\w-]+$/, "math-inline", "math-display"],
    ],
    span: [...(defaultSchema.attributes?.span ?? []), ["className", "math-inline", "math-display"]],
    div: [...(defaultSchema.attributes?.div ?? []), ["className", "math-display"]],
    img: [...(defaultSchema.attributes?.img ?? []), "loading", "decoding"],
  },
  protocols: {
    ...defaultSchema.protocols,
    href: ["http", "https", "mailto", "tel"],
    src: ["http", "https"],
  },
};

function walk(node: Root | ElementContent | RootContent, visit: (el: Element) => void) {
  if (node.type === "element") visit(node);
  if ("children" in node) for (const child of node.children) walk(child, visit);
}

/** Lazy-load images and keep wide tables scrollable. */
function rehypeEnhance() {
  return (tree: Root) => {
    walk(tree, (el) => {
      if (el.tagName === "img") {
        el.properties.loading = "lazy";
        el.properties.decoding = "async";
      }
    });
  };
}

const processor = unified()
  .use(remarkParse)
  .use(remarkGfm)
  .use(remarkMath)
  .use(remarkRehype)
  .use(rehypeSanitize, schema)
  .use(rehypeSlug)
  .use(rehypeEnhance)
  .use(rehypeKatex, { strict: "ignore", trust: false, output: "htmlAndMathml" })
  .use(rehypeStringify);

export type Heading = { id: string; text: string };

export function renderMarkdown(markdown: string): string {
  return String(processor.processSync(markdown ?? ""));
}

/** Level-2 headings for a table of contents, matching the ids rehype-slug produces. */
export function extractHeadings(markdown: string): Heading[] {
  const tree = processor.runSync(processor.parse(markdown ?? "")) as Root;
  const headings: Heading[] = [];
  walk(tree, (el) => {
    if (el.tagName === "h2" && typeof el.properties.id === "string") {
      headings.push({ id: el.properties.id, text: textOf(el) });
    }
  });
  return headings;
}

function textOf(node: ElementContent | Element): string {
  if (node.type === "text") return node.value;
  if ("children" in node) return node.children.map((c) => textOf(c as ElementContent)).join("");
  return "";
}

/** Whether rendered content needs the KaTeX stylesheet. */
export function hasMath(markdown: string): boolean {
  return /\$[^$\n]+\$|\$\$[\s\S]+?\$\$/.test(markdown ?? "");
}

/** Plain-text excerpt from markdown, for meta descriptions and cards. */
export function markdownToPlainText(markdown: string, maxLength = 160): string {
  const text = (markdown ?? "")
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/\$\$[\s\S]*?\$\$/g, " ")
    .replace(/!\[[^\]]*\]\([^)]*\)/g, " ")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/[#>*_`~|-]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  if (text.length <= maxLength) return text;
  const cut = text.slice(0, maxLength - 1);
  return `${cut.slice(0, cut.lastIndexOf(" ") > 40 ? cut.lastIndexOf(" ") : cut.length)}…`;
}
